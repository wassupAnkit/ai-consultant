/** Topics and round-robin section of a catalog row (section overrides first, then the whole domain). */
export function topicsOf(id: string): { section: string; intents: PrimaryIntent[] } {
  const [letter, num] = id.split(".");
  const n = Number(num);
  const range = SECTION_INTENTS[letter!]?.find((r) => n >= r.from && n <= r.to);
  return range ? { section: `${letter}:${range.section}`, intents: range.intents } : { section: letter!, intents: DOMAIN_INTENTS[letter!] ?? [] };
}

