/** Case stages for a row's `S1;S10` list; undefined when any of them applies at every stage. */
export function stagesFor(stages: string): LiveStage[] | undefined {
  const codes = stages.split(";").map((s) => s.trim()).filter(Boolean);
  if (!codes.length) return undefined;
  const out = new Set<LiveStage>();
  for (const c of codes) {
    const mapped = STAGE_CASE_STAGES[c];
    if (!mapped || !mapped.length) return undefined;
    for (const s of mapped) out.add(s);
  }
  return CASE_STAGE_ORDER.filter((s) => out.has(s));
}

export function freshnessOf(cadence: string): Freshness {
  if (cadence === "on_policy_change") return "policy";
  if (cadence === "annual" || cadence === "semi_annual") return "annual";
  return "stable";
}

/** RFC 4180 parser (quoted fields, doubled quotes, CRLF); returns rows of cells, header included. */
export function parseCsv(text: string): string[][] {
  const rows: string[][] = [];
  let row: string[] = [];
  let cell = "";
  let quoted = false;
  for (let i = 0; i < text.length; i++) {
    const ch = text[i]!;
    if (quoted) {
      if (ch === '"' && text[i + 1] === '"') {
        cell += '"';
        i++;
      } else if (ch === '"') quoted = false;
      else cell += ch;
    } else if (ch === '"') quoted = true;
    else if (ch === ",") {
      row.push(cell);
      cell = "";
    } else if (ch === "\n" || ch === "\r") {
      if (ch === "\r" && text[i + 1] === "\n") i++;
      row.push(cell);
      rows.push(row);
      row = [];
      cell = "";
    } else cell += ch;
  }
  if (cell || row.length) {
    row.push(cell);
    rows.push(row);
  }
  return rows;
}

export function csvRecords(text: string): CsvRow[] {
  const [header, ...body] = parseCsv(text);
  if (!header || COLUMNS.some((c, i) => header[i] !== c)) throw new Error("catalog.csv header does not match scripts/catalog.ts COLUMNS");
  return body.map((cells) => Object.fromEntries(COLUMNS.map((c, i) => [c, cells[i] ?? ""])) as CsvRow);
}

type Checklists = Record<PackCountry, Partial<Record<PrimaryIntent, ChecklistItem[]>>>;

/**
 * Per (country, topic): rows of tier ≤ 2 that apply to the country or to `all`,
 * picked round-robin across catalog sections so one checklist spans the topic
 * (visa type, fee, funds, English, documents…) instead of one corner of it; see
 * pickAcrossSections. URL fields and labels that state a figure are skipped.
 */
export function buildChecklists(rows: CsvRow[]): Checklists {
  type Candidate = { row: CsvRow; rank: number; section: string };
  const out = Object.fromEntries(PACK_COUNTRIES.map((c) => [c, {}])) as Checklists;
  for (const [code, country] of Object.entries(COUNTRY_CODES)) {
    const byTopic = new Map<PrimaryIntent, Candidate[]>();
    for (const row of rows) {
      if (!(row.tier === "1" || row.tier === "2") || row.data_type === "url") continue;
      const countries = row.countries.split(";").map((c) => c.trim());
      const specific = countries.includes(code);
      if (!specific && !countries.includes("all")) continue;
      if (findFacts(row.full_name).length) continue;
      const { section, intents } = topicsOf(row.id);
      intents.forEach((intent, rank) => {
        const list = byTopic.get(intent) ?? [];
        list.push({ row, rank, section });
        byTopic.set(intent, list);
      });
    }
    for (const [intent, cands] of byTopic) {
      out[country][intent] = pickAcrossSections(cands).map(({ row }) => {
        const stages = stagesFor(row.stages);
        return { id: row.id, label: row.full_name.trim(), ...(stages ? { stages } : {}), freshness: freshnessOf(row.refresh_cadence) };
      });
    }
  }
  return out;
}

/**
 * Round-robin over sections: sections ordered by how central they are to the topic
 * (rank), then by their best tier; inside a section tier 1 before 2, then id
 * (catalog ids run from the core attribute to its nuances, so the visa fee comes
 * before a country-only TB-test rule). One item per section per pass until the cap.
 */
function pickAcrossSections<T extends { row: CsvRow; rank: number; section: string }>(cands: T[], cap = CAP_PER_TOPIC): T[] {
  const inSection = (a: T, b: T) => Number(a.row.tier) - Number(b.row.tier) || compareIds(a.row.id, b.row.id);
  const groups = new Map<string, T[]>();
  for (const c of cands) groups.set(c.section, [...(groups.get(c.section) ?? []), c]);
  const ordered = [...groups.values()].map((g) => g.sort(inSection));
  ordered.sort((a, b) => a[0]!.rank - b[0]!.rank || Number(a[0]!.row.tier) - Number(b[0]!.row.tier) || compareIds(a[0]!.row.id, b[0]!.row.id));
  const out: T[] = [];
  for (let i = 0; out.length < cap && ordered.some((g) => g.length > i); i++)
    for (const g of ordered) if (g[i] && out.length < cap) out.push(g[i]!);
  return out;
}

type MarketChecklists = Record<Market, Partial<Record<PrimaryIntent, ChecklistItem[]>>>;

/**
 * Per (market, topic): the origin-side items a student from that market needs, whatever the
 * destination. Two pools, both tier ≤ 2 without URL fields or figure-stating labels, mapped to
 * topics exactly like the destination checklists (topicsOf):
 *  1. rows for that market only (`origin:NP` — grading, loans, FX and remittance, origin payment
 *     steps, the Ministry of Education NOC): up to MARKET_OWN_SHARE items, listed first;
 *  2. destination-agnostic rows that vary by nationality (variant_axes `nationality`, countries
 *     `all`: visa-required, biometrics, accepted funds, document variants…) and the source-country
 *     rows that apply to every market: the rest.
 * A pool with too few rows leaves its slots to the other. Each pool is picked round-robin across
 * sections; at most MARKET_CAP_PER_TOPIC items.
 */
export function buildMarketChecklists(rows: CsvRow[]): MarketChecklists {
  type Candidate = { row: CsvRow; rank: number; section: string };
  const eligible = rows.filter((r) => (r.tier === "1" || r.tier === "2") && r.data_type !== "url" && !findFacts(r.full_name).length);
  const generic = eligible.filter((r) => {
    const countries = r.countries.split(";").map((c) => c.trim());
    return countries.includes("all") && (r.variant_axes.split(";").map((a) => a.trim()).includes("nationality") || r.id.startsWith("U."));
  });
  const byTopic = (pool: CsvRow[]) => {
    const out = new Map<PrimaryIntent, Candidate[]>();
    for (const row of pool) {
      const { section, intents } = topicsOf(row.id);
      intents.forEach((intent, rank) => out.set(intent, [...(out.get(intent) ?? []), { row, rank, section }]));
    }
    return out;
  };
  const genericByTopic = byTopic(generic);
  const out = Object.fromEntries(MARKETS.map((m) => [m, {}])) as MarketChecklists;
  for (const [code, market] of Object.entries(MARKET_CODES)) {
    const specificByTopic = byTopic(eligible.filter((r) => r.countries.split(";").map((c) => c.trim()).includes(`origin:${code}`)));
    for (const intent of new Set([...specificByTopic.keys(), ...genericByTopic.keys()])) {
      const own = pickAcrossSections(specificByTopic.get(intent) ?? [], MARKET_CAP_PER_TOPIC);
      const shared = pickAcrossSections(genericByTopic.get(intent) ?? [], MARKET_CAP_PER_TOPIC);
      const nOwn = Math.min(own.length, Math.max(MARKET_OWN_SHARE, MARKET_CAP_PER_TOPIC - shared.length));
      out[market][intent] = [...own.slice(0, nOwn), ...shared.slice(0, MARKET_CAP_PER_TOPIC - nOwn)].map(({ row }) => {
        const stages = stagesFor(row.stages);
        return { id: row.id, label: row.full_name.trim(), ...(stages ? { stages } : {}), freshness: freshnessOf(row.refresh_cadence) };
      });
    }
  }
  return out;
}

function compareIds(a: string, b: string): number {
  return a.slice(0, 1) === b.slice(0, 1) ? Number(a.slice(2)) - Number(b.slice(2)) : a.localeCompare(b);
}

/** The TypeScript module text: countries, markets and topics sorted, items in priority order. */
export function renderChecklistsModule(checklists: Checklists, marketChecklists: MarketChecklists): string {
  const lines = [
    HEADER,
    "// Source: docs/data-model/catalog.csv. Rebuild with `bun run skills:build`.",
    'import type { Market } from "../routing/markets";',
    'import type { PrimaryIntent } from "../schemas/intent.schema";',
    'import type { ChecklistItem, PackCountry } from "./types";',
    "",
    "export const CHECKLISTS: Record<PackCountry, Partial<Record<PrimaryIntent, ChecklistItem[]>>> = {",
  ];
  const block = (slug: string, byTopic: Partial<Record<PrimaryIntent, ChecklistItem[]>>) => {
    lines.push(`  ${slug}: {`);
    for (const topic of Object.keys(byTopic).sort() as PrimaryIntent[]) {
      lines.push(`    ${topic}: [`);
      for (const it of byTopic[topic]!) {
        const stages = it.stages ? `, stages: [${it.stages.map((s) => JSON.stringify(s)).join(", ")}]` : "";
        lines.push(`      { id: ${JSON.stringify(it.id)}, label: ${JSON.stringify(it.label)}${stages}, freshness: ${JSON.stringify(it.freshness)} },`);
      }
      lines.push("    ],");
    }
    lines.push("  },");
  };
  for (const country of [...PACK_COUNTRIES].sort()) block(country, checklists[country]);
  lines.push("};", "", "/** Origin-side checklists per source market (scripts/skills-build.ts buildMarketChecklists). */");
  lines.push("export const MARKET_CHECKLISTS: Record<Market, Partial<Record<PrimaryIntent, ChecklistItem[]>>> = {");
  for (const market of [...MARKETS].sort()) block(market, marketChecklists[market]);
  lines.push("};", "");
  return lines.join("\n");
}

if (import.meta.main) {
  const { values } = parseArgs({ args: Bun.argv.slice(2), options: { check: { type: "boolean", default: false } } });
  const rows = csvRecords(await Bun.file(join(DATA_MODEL_DIR, "catalog.csv")).text());
  const text = renderChecklistsModule(buildChecklists(rows), buildMarketChecklists(rows));
  if (values.check) {
    const current = await Bun.file(GENERATED_FILE).text().catch(() => "");
    if (current !== text) {
      console.error("src/skills/checklists.generated.ts is out of date; run bun run skills:build");
      process.exit(1);
    }
    console.log("checklists up to date");
    process.exit(0);
  }
  await Bun.write(GENERATED_FILE, text);
  console.log(`wrote ${GENERATED_FILE}`);
}
